// Generates tokens.css and tokens.ts from tokens.json and verifies WCAG contrast. No dependencies.
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync(new URL('./tokens.json', import.meta.url)));
const get = (path) => t.primitive[path];
const lum = (hex) => { const c = [1,3,5].map(i => parseInt(hex.slice(i,i+2),16)/255).map(v => v<=0.03928 ? v/12.92 : ((v+0.055)/1.055)**2.4); return 0.2126*c[0]+0.7152*c[1]+0.0722*c[2]; };
const ratio = (a,b) => { const [x,y] = [lum(a),lum(b)].sort((p,q)=>q-p); return (x+0.05)/(y+0.05); };
let fail = 0; const report = [];
for (const [theme, checks] of Object.entries(t['contrast-checks'])) {
  for (const [fg, bg, min] of checks) {
    const r = ratio(get(t.semantic[theme][fg]), get(t.semantic[theme][bg]));
    const ok = r >= min; if (!ok) fail++;
    report.push(`${ok?'PASS':'FAIL'}  ${theme.padEnd(10)} ${fg} on ${bg}: ${r.toFixed(2)} (min ${min})`);
  }
}
console.log(report.join('\n')); console.log(fail ? `\n${fail} FAILED` : '\nAll contrast checks passed');
const block = (sel, vars) => `${sel} {\n${vars.map(([k,v]) => `  --${k}: ${v};`).join('\n')}\n}\n`;
const themeVars = (th) => Object.entries(t.semantic[th]).map(([k,v]) => [`color-${k}`, get(v)]);
const common = [
  ...Object.entries(t.typography.size).map(([k,v]) => [`font-size-${k}`, v]),
  ['font-family-ui', t.typography['family-ui']], ['font-family-display', t.typography['family-display']],
  ...Object.entries(t.typography['line-height']).map(([k,v]) => [`line-height-${k}`, v]),
  ...Object.entries(t.space).map(([k,v]) => [`space-${k}`, v]),
  ...Object.entries(t.radius).map(([k,v]) => [`radius-${k}`, v]),
  ...Object.entries(t.shadow).map(([k,v]) => [`shadow-${k}`, v]),
  ...Object.entries(t.motion).map(([k,v]) => [`motion-${k}`, v]),
  ['font-family-latin', t.typography['family-latin']], ['gradient-gold', t.gradient.gold],
  ...Object.entries(t.typography.weight).map(([k,v]) => [`font-weight-${k}`, v]),
  ['touch-min-target', t.touch['min-target']]
];
let css = '/* GENERATED by build.mjs from tokens.json. Do not edit by hand. */\n';
css += block(':root,\n[data-theme="light"]', [...themeVars('light'), ...common]);
css += block('[data-theme="dark"]', themeVars('dark'));
css += '@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n' + themeVars('dark').map(([k,v]) => `    --${k}: ${v};`).join('\n') + '\n  }\n}\n';
css += '@media (prefers-reduced-motion: reduce) {\n  :root { ' + ['press','small','card','page','success','progress'].map(k => `--motion-${k}: 0ms;`).join(' ') + ' }\n}\n';
writeFileSync(new URL('./tokens.css', import.meta.url), css);
const resolved = Object.fromEntries(Object.keys(t.semantic).map(th => [th, Object.fromEntries(Object.entries(t.semantic[th]).map(([k,v]) => [k, get(v)]))]));
const ts = `// GENERATED by build.mjs from tokens.json. Do not edit by hand.\nexport const colors = ${JSON.stringify(resolved, null, 2)} as const;\nexport const space = ${JSON.stringify(t.space)} as const;\nexport const radius = ${JSON.stringify(t.radius)} as const;\nexport const fontSize = ${JSON.stringify(t.typography.size)} as const;\nexport const minTouchTarget = 48;\n`;
writeFileSync(new URL('./tokens.ts', import.meta.url), ts);
process.exit(fail ? 1 : 0);
